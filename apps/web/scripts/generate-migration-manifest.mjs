import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const webRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const migrationsRoot = resolve(webRoot, "drizzle");
const journalPath = resolve(migrationsRoot, "meta", "_journal.json");
const outputPath = resolve(
  webRoot,
  "src",
  "generated",
  "migration-manifest.ts",
);
const checkOnly = process.argv.includes("--check");

const journal = JSON.parse(readFileSync(journalPath, "utf8"));
const migrations = journal.entries.map((entry) => {
  const sqlPath = resolve(migrationsRoot, `${entry.tag}.sql`);
  if (!existsSync(sqlPath)) {
    throw new Error(`Migration journal entry ${entry.tag} has no SQL file.`);
  }

  return {
    tag: entry.tag,
    createdAt: String(entry.when),
    hash: createHash("sha256").update(readFileSync(sqlPath)).digest("hex"),
  };
});

const generated =
  `// Generated by scripts/generate-migration-manifest.mjs. Do not edit by hand.\n` +
  `export const EXPECTED_DATABASE_MIGRATIONS = ${JSON.stringify(migrations, null, 2)} as const;\n`;

if (checkOnly) {
  const current = existsSync(outputPath)
    ? readFileSync(outputPath, "utf8")
    : "";
  if (current !== generated) {
    throw new Error(
      "Migration manifest is stale. Run `pnpm --filter @school-sis/web run db:manifest`.",
    );
  }
  console.log(
    `Migration manifest is current (${migrations.length} migration${migrations.length === 1 ? "" : "s"}).`,
  );
} else {
  writeFileSync(outputPath, generated);
  console.log(
    `Wrote migration manifest (${migrations.length} migration${migrations.length === 1 ? "" : "s"}).`,
  );
}
