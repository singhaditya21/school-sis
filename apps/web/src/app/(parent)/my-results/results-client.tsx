'use client';

import { useEffect, useState } from 'react';
import { Card, CardContent, CardHeader, CardTitle, CardDescription } from '@/components/ui/card';
import { Badge } from '@/components/ui/badge';
import { Button } from '@/components/ui/button';
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from '@/components/ui/table';
import { BarChart, Bar, XAxis, YAxis, CartesianGrid, Tooltip, ResponsiveContainer } from 'recharts';
import { Download, TrendingUp } from 'lucide-react';
import jsPDF from 'jspdf';
import { toast } from 'sonner';
import { ParentTopBar } from '@/components/parent/parent-top-bar';
import { useParentChildren } from '@/components/parent/use-parent-children';
import { getChildResults, type ChildResultRow } from '../actions';

interface ExamGroup {
    examId: string;
    examName: string;
    examType: string;
    examStartDate: string | null;
    publishedOn: string | null;
    rows: ChildResultRow[];
}

function groupByExam(results: ChildResultRow[]): ExamGroup[] {
    const groups = new Map<string, ExamGroup>();
    for (const row of results) {
        const existing = groups.get(row.examId);
        if (existing) {
            existing.rows.push(row);
        } else {
            groups.set(row.examId, {
                examId: row.examId,
                examName: row.examName,
                examType: row.examType,
                examStartDate: row.examStartDate,
                publishedOn: row.publishedOn,
                rows: [row],
            });
        }
    }
    return [...groups.values()];
}

export function ResultsClient() {
    const { students, selectedId, loading: childrenLoading, error: childrenError } = useParentChildren();
    // Keyed by child so a response for a previously selected child can never be
    // rendered under the newly selected one.
    const [fetched, setFetched] = useState<{
        key: string;
        results: ChildResultRow[];
        childName: string | null;
    } | null>(null);

    useEffect(() => {
        if (childrenLoading || !selectedId) return;

        let cancelled = false;
        const key = selectedId;
        getChildResults(selectedId)
            .then((res) => {
                if (cancelled) return;
                setFetched({ key, results: res?.results ?? [], childName: res?.child.name ?? null });
            })
            .catch(() => {
                if (cancelled) return;
                setFetched({ key, results: [], childName: null });
                toast.error('Could not load academic records.');
            });

        return () => {
            cancelled = true;
        };
    }, [selectedId, childrenLoading]);

    const current = fetched?.key === selectedId ? fetched : null;
    const results = current?.results ?? [];
    const childName = current?.childName ?? null;
    const loading = childrenLoading || (selectedId !== null && current === null);

    function examAverage(group: ExamGroup): number | null {
        const scored = group.rows.filter((r) => !r.isAbsent && r.percentage !== null);
        if (scored.length === 0) return null;
        return Math.round(scored.reduce((sum, r) => sum + (r.percentage ?? 0), 0) / scored.length);
    }

    function generatePDF(group: ExamGroup) {
        const doc = new jsPDF();
        doc.setFontSize(20);
        doc.text(group.examName, 14, 20);

        doc.setFontSize(12);
        doc.setTextColor(100);
        doc.text(childName ?? 'Student', 14, 29);
        doc.text('Generated by ScholarMind SIS', 14, 36);

        let yPos = 50;
        doc.setTextColor(0);
        doc.setFontSize(10);
        doc.setTextColor(150);
        doc.text('Subject', 14, yPos);
        doc.text('Marks', 90, yPos);
        doc.text('Max', 120, yPos);
        doc.text('%', 145, yPos);
        doc.text('Grade', 170, yPos);
        yPos += 4;
        doc.line(14, yPos, 195, yPos);
        yPos += 8;
        doc.setTextColor(0);

        for (const row of group.rows) {
            if (yPos > 280) {
                doc.addPage();
                yPos = 20;
            }
            doc.text(row.subject, 14, yPos);
            doc.text(row.isAbsent ? 'Absent' : String(row.marksObtained ?? '—'), 90, yPos);
            doc.text(String(row.maxMarks), 120, yPos);
            doc.text(row.isAbsent || row.percentage === null ? '—' : `${row.percentage}%`, 145, yPos);
            doc.text(row.grade ?? '—', 170, yPos);
            yPos += 9;
        }

        const average = examAverage(group);
        if (average !== null) {
            yPos += 4;
            doc.setFontSize(11);
            doc.text(`Average: ${average}%`, 14, yPos);
        }

        doc.save(`${group.examName.replace(/\s+/g, '_')}_${(childName ?? 'student').replace(/\s+/g, '_')}.pdf`);
    }

    const groups = groupByExam(results);

    return (
        <div className="mx-auto max-w-7xl space-y-6 pb-12">
            <ParentTopBar students={students} selectedId={selectedId} loading={childrenLoading} />

            <div className="border-b pb-6">
                <h1 className="text-2xl font-semibold tracking-tight text-foreground">Academic records</h1>
                <p className="mt-1 text-sm text-muted-foreground">
                    {childName ? `Published exam results for ${childName}` : 'Published exam results'}
                </p>
            </div>

            {childrenError && (
                <div className="rounded-lg border border-red-200 bg-red-50 p-4 text-sm text-red-700">
                    {childrenError}
                </div>
            )}

            {loading ? (
                <div className="py-12 text-center text-sm text-muted-foreground">Loading academic records…</div>
            ) : students.length === 0 ? (
                <div className="rounded-lg border border-dashed bg-muted p-12 text-center text-muted-foreground">
                    No child is linked to your account yet, so there are no results to show.
                </div>
            ) : groups.length === 0 ? (
                <div className="rounded-lg border border-dashed bg-muted p-12 text-center text-muted-foreground">
                    <p className="font-medium text-muted-foreground">No published results yet</p>
                    <p className="mt-1 text-sm">
                        Marks become visible here only after the school publishes the exam.
                    </p>
                </div>
            ) : (
                groups.map((group) => {
                    const average = examAverage(group);
                    const chartData = group.rows
                        .filter((r) => !r.isAbsent && r.percentage !== null)
                        .map((r) => ({ subject: r.subject, percentage: r.percentage as number }));

                    return (
                        <Card key={group.examId} className="overflow-hidden rounded-md border-border shadow-sm">
                            <CardHeader className="flex flex-row items-center justify-between border-b bg-muted px-6 py-4">
                                <div>
                                    <CardTitle className="text-lg font-semibold text-foreground">
                                        {group.examName}
                                    </CardTitle>
                                    <CardDescription className="mt-1 text-xs font-medium">
                                        {group.examType.replace(/_/g, ' ')}
                                        {group.examStartDate ? ` · ${group.examStartDate}` : ''}
                                        {group.publishedOn ? ` · published ${group.publishedOn}` : ''}
                                    </CardDescription>
                                </div>
                                <div className="flex items-center gap-4">
                                    {average !== null && (
                                        <Badge
                                            variant="secondary"
                                            className="border-border px-3 py-1 font-mono text-sm"
                                        >
                                            Average: {average}%
                                        </Badge>
                                    )}
                                    <Button
                                        size="sm"
                                        variant="outline"
                                        className="h-8 text-xs font-medium"
                                        onClick={() => generatePDF(group)}
                                    >
                                        <Download className="mr-2 h-4 w-4" /> Export PDF
                                    </Button>
                                </div>
                            </CardHeader>
                            <CardContent className="p-0">
                                <div className="grid divide-y border-b lg:grid-cols-3 lg:divide-x lg:divide-y-0">
                                    <div className="overflow-x-auto p-0 lg:col-span-2">
                                        <Table>
                                            <TableHeader className="bg-muted">
                                                <TableRow>
                                                    <TableHead className="font-medium text-muted-foreground">Subject</TableHead>
                                                    <TableHead className="text-right font-medium text-muted-foreground">
                                                        Score
                                                    </TableHead>
                                                    <TableHead className="text-right font-medium text-muted-foreground">
                                                        Percentage
                                                    </TableHead>
                                                    <TableHead className="font-medium text-muted-foreground">Grade</TableHead>
                                                    <TableHead className="font-medium text-muted-foreground">Remarks</TableHead>
                                                </TableRow>
                                            </TableHeader>
                                            <TableBody>
                                                {group.rows.map((row, idx) => {
                                                    const failed =
                                                        !row.isAbsent &&
                                                        row.passingMarks !== null &&
                                                        row.marksObtained !== null &&
                                                        row.marksObtained < row.passingMarks;

                                                    return (
                                                        <TableRow key={`${row.examId}-${row.subject}-${idx}`}>
                                                            <TableCell className="font-medium text-foreground">
                                                                {row.subject}
                                                            </TableCell>
                                                            <TableCell className="text-right font-mono text-muted-foreground">
                                                                {row.isAbsent ? (
                                                                    <span className="text-muted-foreground">Absent</span>
                                                                ) : (
                                                                    <>
                                                                        {row.marksObtained ?? '—'}{' '}
                                                                        <span className="text-muted-foreground">
                                                                            / {row.maxMarks}
                                                                        </span>
                                                                    </>
                                                                )}
                                                            </TableCell>
                                                            <TableCell className="text-right font-mono font-medium text-foreground">
                                                                {row.isAbsent || row.percentage === null
                                                                    ? '—'
                                                                    : `${row.percentage}%`}
                                                            </TableCell>
                                                            <TableCell>
                                                                <Badge
                                                                    variant={
                                                                        row.isAbsent || failed
                                                                            ? 'destructive'
                                                                            : 'secondary'
                                                                    }
                                                                    className="rounded-sm px-2 font-mono text-[10px]"
                                                                >
                                                                    {row.grade ?? (row.isAbsent ? 'AB' : 'N/A')}
                                                                </Badge>
                                                            </TableCell>
                                                            <TableCell className="text-sm text-muted-foreground">
                                                                {row.remarks ?? (failed ? 'Below passing marks' : '—')}
                                                            </TableCell>
                                                        </TableRow>
                                                    );
                                                })}
                                            </TableBody>
                                        </Table>
                                    </div>

                                    <div className="bg-muted/30 p-6">
                                        <h2 className="mb-4 flex items-center text-xs font-semibold uppercase tracking-wider text-muted-foreground">
                                            <TrendingUp className="mr-2 h-4 w-4" /> Performance by subject
                                        </h2>
                                        {chartData.length === 0 ? (
                                            <p className="text-sm text-muted-foreground">No scored subjects to chart.</p>
                                        ) : (
                                            <div className="h-[200px] w-full">
                                                <ResponsiveContainer width="100%" height="100%">
                                                    <BarChart
                                                        data={chartData}
                                                        margin={{ top: 10, right: 10, left: -20, bottom: 0 }}
                                                    >
                                                        <CartesianGrid
                                                            strokeDasharray="3 3"
                                                            vertical={false}
                                                            stroke="#e2e8f0"
                                                        />
                                                        <XAxis
                                                            dataKey="subject"
                                                            tick={{ fontSize: 10 }}
                                                            tickLine={false}
                                                            axisLine={false}
                                                        />
                                                        <YAxis
                                                            tick={{ fontSize: 10 }}
                                                            tickLine={false}
                                                            axisLine={false}
                                                            domain={[0, 100]}
                                                        />
                                                        <Tooltip
                                                            cursor={{ fill: '#f1f5f9' }}
                                                            contentStyle={{
                                                                borderRadius: '6px',
                                                                fontSize: '12px',
                                                                border: 'none',
                                                                boxShadow: '0 4px 6px -1px rgb(0 0 0 / 0.1)',
                                                            }}
                                                        />
                                                        <Bar
                                                            dataKey="percentage"
                                                            fill="#0f172a"
                                                            radius={[4, 4, 0, 0]}
                                                            maxBarSize={40}
                                                        />
                                                    </BarChart>
                                                </ResponsiveContainer>
                                            </div>
                                        )}
                                    </div>
                                </div>
                            </CardContent>
                        </Card>
                    );
                })
            )}
        </div>
    );
}
